def _c(code, name, marks, scope, assessed_at, *levels):
    """One criterion; `levels` are (mark band, description) pairs in LEVELS order."""
    return {"code": code, "name": name, "marks": marks, "scope": scope, "assessed_at": assessed_at,
            "levels": [{"marks": band, "description": text} for band, text in levels]}


